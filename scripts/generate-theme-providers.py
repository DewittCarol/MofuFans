"""Generate the small React adapters in each independent Next application.

Pure data/types/CSS mapping are shared. Keeping adapters under each app makes
React resolve from that app's own node_modules, including static builds.
"""
from pathlib import Path
root = Path(__file__).resolve().parents[1]
source = (root/'shared/theme-provider.template.tsx').read_text(encoding='utf-8')
for app in ('frontend','admin'):
    (root/app/'src/lib/site-theme.tsx').write_bytes(('// Generated by scripts/generate-theme-providers.py\n'+source.replace('__ADMIN__',str(app=='admin').lower())).encode('utf-8'))
